/** Applica data-i18n, data-i18n-ph, data-i18n-title, data-i18n-aria agli elementi statici. */
export function applyStatic() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPh);
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    setTip(el, t(el.dataset.i18nTitle));
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });
  const meta = document.querySelector('meta[name="description"]');
  if (meta) meta.content = t('meta.description');
}

export function onLangChange(cb) {
  window.addEventListener('wf:langchange', cb);
}

export function emitLangChange() {
  applyStatic();
  window.dispatchEvent(new Event('wf:langchange'));
}
